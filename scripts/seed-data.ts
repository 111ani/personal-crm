const emailDomains = ["example.com", "example.org", "example.net"];

const translitMap: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z",
  и: "i", й: "y", к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r",
  с: "s", т: "t", у: "u", ф: "f", х: "kh", ц: "ts", ч: "ch", ш: "sh",
  щ: "shch", ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
};

/** Small seeded PRNG (mulberry32) */
function createRandom(seed: number) {
  let state = seed >>> 0;
  const next = () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  return {
    next,
    int: (min: number, max: number) => min + Math.floor(next() * (max - min + 1)),
    chance: (probability: number) => next() < probability,
    pick: <T>(items: readonly T[]): T => items[Math.floor(next() * items.length)],
  };
}

type Random = ReturnType<typeof createRandom>;

function feminineSurname(surname: string) {
  if (/(ский|цкий)$/.test(surname)) {
    return surname.slice(0, -2) + "ая";
  }
  if (/(ов|ев|ёв|ин|ын)$/.test(surname)) {
    return surname + "а";
  }
  // Ким, Цой, Шевченко, Черных - the same for both genders
  return surname;
}

function byGender(value: Gendered, gender: Gender) {
  if (typeof value === "string") {
    return value;
  }
  return gender === "m" ? value[0] : value[1];
}

function translit(value: string) {
  return [...value.toLowerCase()].map((char) => translitMap[char] ?? char).join("");
}

function makePhone(random: Random) {
  const digits = (count: number) =>
    Array.from({ length: count }, () => random.int(0, 9)).join("");
  return `+7 9${digits(2)} ${digits(3)}-${digits(2)}-${digits(2)}`;
}

function makeEmail(random: Random, firstName: string, lastName: string) {
  const first = translit(firstName);
  const last = translit(lastName);
  const local = random.pick([
    `${first}.${last}`,
    `${first[0]}.${last}`,
    `${last}.${first}`,
    `${first}${last}${random.int(1, 99)}`,
    `${first}_${last}`,
  ]);
  return `${local}@${random.pick(emailDomains)}`;
}

function randomDateBetween(random: Random, from: Date, to: Date) {
  const span = to.getTime() - from.getTime();
  return new Date(from.getTime() + Math.floor(random.next() * span));
}

const noteCountWeights: [count: number, weight: number][] = [
  [0, 35],
  [1, 30],
  [2, 18],
  [3, 10],
  [4, 5],
  [5, 2],
];

function pickNoteCount(random: Random) {
  let roll = random.next() * 100;
  for (const [count, weight] of noteCountWeights) {
    roll -= weight;
    if (roll < 0) {
      return count;
    }
  }
  return 0;
}

export function generateSeedData(count: number, now: Date, seed = 20261008) {
  const random = createRandom(seed);
  const contactRows: NewContact[] = [];
  const noteRows: NewNote[] = [];
  const usedNames = new Set<string>();
  const fourYearsAgo = new Date(now.getTime() - 4 * 365 * 24 * 60 * 60 * 1000);

  while (contactRows.length < count) {
    const gender: Gender = random.chance(0.5) ? "m" : "f";
    const firstName = random.pick(gender === "m" ? maleNames : femaleNames);
    const baseSurname = random.pick(surnames);
    const lastName = gender === "m" ? baseSurname : feminineSurname(baseSurname);
    const name = `${firstName} ${lastName}`;
    if (usedNames.has(name)) {
      continue;
    }
    usedNames.add(name);

    const id = randomUUID();
    const createdAt = randomDateBetween(random, fourYearsAgo, now);

    const noteDates = Array.from({ length: pickNoteCount(random) }, () =>
      randomDateBetween(random, createdAt, now),
    ).sort((a, b) => a.getTime() - b.getTime());
    const usedTemplates = new Set<Gendered>();
    for (const createdAtNote of noteDates) {
      let template = random.pick(noteTemplates);
      while (usedTemplates.has(template)) {
        template = random.pick(noteTemplates);
      }
      usedTemplates.add(template);
      noteRows.push({
        contactId: id,
        body: byGender(template, gender),
        createdAt: createdAtNote,
      });
    }

    contactRows.push({
      id,
      name,
      about: random.chance(0.9) ? byGender(random.pick(roles), gender) : null,
      howWeMet: random.chance(0.8)
        ? byGender(random.pick(howWeMetOptions), gender)
        : null,
      phone: random.chance(0.85) ? makePhone(random) : null,
      email: random.chance(0.65) ? makeEmail(random, firstName, lastName) : null,
      createdAt,
      updatedAt: noteDates.at(-1) ?? createdAt,
    });
  }

  return { contactRows, noteRows };
}
